/* Builds app/app.js from app/app.jsx (the page's code: React with JSX) and stamps index.html with its version, so
   browsers load ready-made JavaScript instead of compiling the app themselves on every visit.
     node tools/build.mjs          build
     node tools/build.mjs --check  fail if app/app.js or index.html is not up to date with app/app.jsx (CI) */
import fs from "fs";
import path from "path";
import crypto from "crypto";
import { createRequire } from "module";
import { fileURLToPath } from "url";

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, "..");
const require = createRequire(import.meta.url);
const Babel = require("@babel/standalone");

const SRC = path.join(repo, "app", "app.jsx"), OUT = path.join(repo, "app", "app.js"), HTML = path.join(repo, "index.html");
const BANNER = "/* Built from app/app.jsx by tools/build.mjs. Do not edit this file: change app/app.jsx, then run node tools/build.mjs. */\n";

const src = fs.readFileSync(SRC, "utf8");
const built = BANNER + Babel.transform(src, { presets: ["react"], comments: false, compact: true, filename: "app.jsx" }).code + "\n";
const v = crypto.createHash("sha256").update(built).digest("hex").slice(0, 10);
const html = fs.readFileSync(HTML, "utf8");
const tag = /<script src="app\/app\.js(\?v=[0-9a-f]*)?"><\/script>/;
if (!tag.test(html)) { console.error("index.html has no <script src=\"app/app.js\"> tag."); process.exit(1); }
const nextHtml = html.replace(tag, `<script src="app/app.js?v=${v}"></script>`);

if (process.argv.includes("--check")) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  const bad = [];
  if (cur !== built) bad.push("app/app.js is not built from the current app/app.jsx");
  if (nextHtml !== html) bad.push("index.html does not point at the current app/app.js version");
  if (bad.length) { console.error("Out of date: " + bad.join("; ") + ". Run: node tools/build.mjs, then commit."); process.exit(1); }
  console.log("Build is up to date (app.js " + v + ").");
} else {
  fs.writeFileSync(OUT, built);
  if (nextHtml !== html) fs.writeFileSync(HTML, nextHtml);
  console.log("Built app/app.js (" + Math.round(built.length / 1024) + " KB, v " + v + ").");
}
